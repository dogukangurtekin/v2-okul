<h1 class="text-2xl font-bold">Gizlilik ve Kişisel Verilerin Korunması (KVKK)</h1>
<p class="text-sm text-amber-700 bg-amber-50 p-2 rounded">Bu metin şablondur; yayına almadan önce okulunuzun hukuk danışmanı tarafından gözden geçirilmeli ve kurum bilgileri eklenmelidir.</p>
<h2 class="font-semibold">Hangi verileri işliyoruz?</h2>
<p>Ad soyad, öğrenci numarası, sınıf, veli adı ve telefonu, platformdaki ilerleme (XP, ödev, ders ve oyun sonuçları), oturum etkinlik kayıtları ve gönderdiğiniz mesajlar.</p>
<h2 class="font-semibold">Amaç ve hukuki sebep</h2>
<p>Eğitim hizmetinin yürütülmesi, öğrenci gelişiminin izlenmesi ve velilerin bilgilendirilmesi. Reşit olmayan öğrencilerin verileri veli/vasi bilgisi dahilinde işlenir.</p>
<h2 class="font-semibold">Saklama ve paylaşım</h2>
<p>Veriler yalnızca okul yönetimi ve ilgili öğretmenlerle paylaşılır. Etkinlik günlükleri 30 gün sonra silinir. Veli raporları imzalı ve süreli bağlantıyla paylaşılır.</p>
<h2 class="font-semibold">Haklarınız</h2>
<p>KVKK madde 11 uyarınca verilerinize erişme, düzeltme ve silme talebinde bulunabilirsiniz. Başvuru için okul yönetimine yazın.</p>
